        VALUES (9002, current_timestamp - interval '1 day',
            '1c5a0b2e4f6d8a0c2e4f6d8a0c2e4f6d8a0c2e4f', '')
    $$,
    '23514',
    NULL,
    'a capture cannot claim a bundle at no location'
