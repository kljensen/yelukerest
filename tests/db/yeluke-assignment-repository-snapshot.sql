-- Constraints
-- ---------------------------------------------------------------------------
-- Written against the base table as the test superuser, because these are
-- constraints rather than policy: they hold whoever is asking.

SELECT lives_ok(
    $$
        INSERT INTO data.assignment_repository_snapshot
            (id, assignment_repository_id, effective_closed_at, captured_at,
             commit_sha, bundle_uri)
        VALUES (8001, 9001,
            current_timestamp - interval '1 day',
            current_timestamp - interval '23 hours',
            '1c5a0b2e4f6d8a0c2e4f6d8a0c2e4f6d8a0c2e4f',
            'file:///srv/snapshots/exam-1/9001.bundle')
    $$,
    'a capture records the commit that was graded and where its bundle went'
);

-- git is midway through the SHA-1 to SHA-256 migration, so both lengths are
-- real.
SELECT lives_ok(
    $$
        INSERT INTO data.assignment_repository_snapshot
            (id, assignment_repository_id, effective_closed_at, captured_at,
             commit_sha, bundle_uri)
        VALUES (8003, 9003,
            current_timestamp - interval '1 day',
            current_timestamp - interval '23 hours',
            '0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef',
            'file:///srv/snapshots/project-update-1/9003.bundle')
    $$,
    'a sha-256 object name is a commit too'
);

-- Uppercase would make one commit into two strings.
SELECT throws_ok(
