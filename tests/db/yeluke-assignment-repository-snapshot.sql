-- data.assignment_repository_snapshot: what each student's repository contained
-- at their effective deadline (#22).
--
-- Sample data this file leans on: users 1 (abc123, student, team bright-fog),
-- 2 (bde456, student, team hazy-mountain), 3 (klj39, faculty), 4 (jlb325, ta,
-- no team); assignments exam-1 and team-selection (individual, published),
-- js-koans (individual, draft) and project-update-1 (team, published); and the
-- shipped exception giving team hazy-mountain until 3019 on project-update-1.
--
-- Every assignment in the sample data closes in 3018, so nothing is ever due.
-- The deadlines below are moved into the past deliberately, and `current_timestamp`
-- is fixed for the whole of this transaction, so a timestamp written here and the
-- one the view computes are the same value rather than merely close.
--
-- Repository and snapshot ids are given explicitly. The columns are GENERATED BY
-- DEFAULT, and a known id is what lets the assertions name a row instead of
-- chasing a sequence.

SELECT plan(39);

-- ---------------------------------------------------------------------------
-- Shape and privileges
-- ---------------------------------------------------------------------------

SELECT has_table(
    'data', 'assignment_repository_snapshot',
    'assignment_repository_snapshot table should record deadline captures'
);

SELECT view_owner_is(
    'api', 'assignment_repository_snapshots', 'api',
    'api.assignment_repository_snapshots should be owned by the api role, or its RLS policy never applies'
);

SELECT view_owner_is(
    'api', 'assignment_repository_snapshots_due', 'api',
    'api.assignment_repository_snapshots_due should be owned by the api role, or its RLS policy never applies'
);

SELECT table_privs_are(
    'api', 'assignment_repository_snapshots', 'faculty',
    ARRAY['SELECT', 'INSERT', 'UPDATE', 'DELETE'],
    'faculty should have CRUD on view "api.assignment_repository_snapshots"'
);

SELECT table_privs_are(
    'api', 'assignment_repository_snapshots', 'student', ARRAY['SELECT'],
    'student should only be granted SELECT on view "api.assignment_repository_snapshots"'
);

SELECT table_privs_are(
    'api', 'assignment_repository_snapshots', 'ta', ARRAY['SELECT'],
    'ta should only be granted SELECT on view "api.assignment_repository_snapshots"'
);

SELECT table_privs_are(
    'api', 'assignment_repository_snapshots', 'anonymous', ARRAY[]::text[],
    'anonymous should be granted nothing on view "api.assignment_repository_snapshots"'
);

-- The queue carries every student's effective deadline and is read by the
-- snapshot runner alone.
SELECT table_privs_are(
    'api', 'assignment_repository_snapshots_due', 'faculty', ARRAY['SELECT'],
    'faculty should be able to read the snapshot queue'
);

SELECT table_privs_are(
    'api', 'assignment_repository_snapshots_due', 'student', ARRAY[]::text[],
    'student should be granted nothing on the snapshot queue'
);

SELECT table_privs_are(
    'api', 'assignment_repository_snapshots_due', 'ta', ARRAY[]::text[],
    'ta should be granted nothing on the snapshot queue'
);

SELECT table_privs_are(
    'data', 'assignment_repository_snapshot', 'student', ARRAY[]::text[],
    'student should be granted nothing on "data.assignment_repository_snapshot"'
);

