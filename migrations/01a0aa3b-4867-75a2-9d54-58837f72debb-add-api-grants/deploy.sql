-- One row per granted assignment, carrying the identity attributes the
-- consumer may see for that assignment's submitters. Any subset of the four,
-- possibly none: a leaderboard needs nicknames, a URL lister needs nothing.
CREATE TABLE data.api_grant_assignment (
    grant_id int NOT NULL REFERENCES data.api_grant (id),
    assignment_slug text NOT NULL REFERENCES data.assignment (slug),
    identity text[] NOT NULL CHECK (
    -- `<@` also refuses a NULL element, which is never a subset of anything.
    identity <@ ARRAY['netid', 'name', 'nickname', 'team_nickname']::text[]),
    PRIMARY KEY (grant_id, assignment_slug)
)
; CREATE INDEX api_grant_assignment_assignment_slug_idx
ON data.api_grant_assignment USING btree (assignment_slug)
; ALTER TABLE data.api_grant_assignment
    OWNER TO yelukerest_migrator
; COMMENT ON TABLE data.api_grant_assignment IS 'An assignment a grant covers, with the submitter identity attributes the consumer may see. Fixed at creation.'
;
-- One row per granted field. The key to data.assignment_field is composite
-- because a field slug such as `url` recurs across assignments (ADR 0005): a
-- grant names a field OF an assignment, never a slug that matches everywhere.
CREATE TABLE data.api_grant_assignment_field (
    grant_id int NOT NULL,
    assignment_slug text NOT NULL,
    field_slug text NOT NULL,
    PRIMARY KEY (grant_id, assignment_slug, field_slug),
    FOREIGN KEY (grant_id, assignment_slug) REFERENCES data.api_grant_assignment (grant_id, assignment_slug),
    FOREIGN KEY (field_slug, assignment_slug) REFERENCES data.assignment_field (slug, assignment_slug)
)
; CREATE INDEX api_grant_assignment_field_field_idx
ON data.api_grant_assignment_field USING btree (field_slug, assignment_slug)
