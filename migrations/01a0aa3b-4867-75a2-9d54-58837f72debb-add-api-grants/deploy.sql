-- Deployed inside a transaction Zapadka opens and commits.
-- Do not write BEGIN, COMMIT, ROLLBACK, or SAVEPOINT here.
-- Data grants for consuming apps, step 1 of 3: the permission as data
-- (issue #384, ADR 0005).
--
-- An app that consumes course data -- the voting app that lists every
-- submitted URL for one assignment, say -- has had no credential of its own.
-- It ran on a faculty token, which reads everything faculty reads. This
-- records instead exactly what such an app may see: which assignments, which
-- identity attributes of the submitter, which fields. The credential that
-- presents a grant, and the reader that honours it, arrive in the next two
-- migrations; this one is the storage and its lifecycle.
--
-- Two rules shape everything below. A grant is immutable once created: to
-- change what an app may see, revoke the grant and create another, so the
-- record of what each credential could ever read is never rewritten. And every
-- foreign key is restrictive: a field a grant names cannot be renamed or
-- dropped while the grant row exists, revoked or not, because the grant would
-- otherwise silently stop meaning what it meant.
-- ---------------------------------------------------------------------------
-- Storage
-- ---------------------------------------------------------------------------
CREATE TABLE data.api_grant (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CHECK (char_length(name) BETWEEN 3 AND 80),
    created_by int NOT NULL REFERENCES data."user" (id),
    created_at timestamp with time zone NOT NULL DEFAULT current_timestamp,
    expires_at timestamp with time zone NOT NULL,
    revoked_by int REFERENCES data."user" (id),
    revoked_at timestamp with time zone,
    CONSTRAINT api_grant_expires_after_creation CHECK (expires_at > created_at),
    CONSTRAINT api_grant_max_lifetime CHECK (
    -- The cap personal access tokens carry (01a04817-bound-api-token-lifetime).
    expires_at <= (created_at + '180 days'::interval)),
    CONSTRAINT api_grant_revocation_names_actor_and_time CHECK ((revoked_at IS NULL) = (revoked_by IS NULL)),
    CONSTRAINT api_grant_revoked_after_creation CHECK (revoked_at >= created_at)
)
;
-- tests/db/foreign-key-indexes.sql requires an index led by every referencing
-- column.
CREATE INDEX api_grant_created_by_idx
ON data.api_grant USING btree (created_by)
