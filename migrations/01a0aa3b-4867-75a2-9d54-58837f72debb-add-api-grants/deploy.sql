-- ---------------------------------------------------------------------------
-- Revoking a grant
-- ---------------------------------------------------------------------------
-- Faculty only, and one-way. A second revoke changes nothing and reports the
-- first actor and time: revocation is a fact about when access ended.
-- The caller is resolved to a current faculty row rather than trusted from the
-- claim alone, so revoked_by always names a real person.
CREATE FUNCTION api.revoke_api_grant(p_id int) RETURNS TABLE (id int, name text, revoked_at timestamp with time zone, revoked_by int) SECURITY DEFINER LANGUAGE plpgsql SET search_path TO pg_catalog, api, data, request, pg_temp AS $$
DECLARE
    caller_id int;
BEGIN
    IF request.user_role() IS DISTINCT FROM 'faculty' THEN
        RAISE insufficient_privilege USING MESSAGE = 'only faculty may revoke an api grant';
    END IF;
    SELECT u.id INTO caller_id FROM data."user" u WHERE u.id = request.user_id() AND u.role = 'faculty';
    IF caller_id IS NULL THEN
        RAISE insufficient_privilege USING MESSAGE = 'the caller is not a current faculty member';
    END IF;

    UPDATE data.api_grant g
       SET revoked_at = current_timestamp, revoked_by = caller_id
     WHERE g.id = p_id AND g.revoked_at IS NULL;

    RETURN QUERY
    SELECT g.id, g.name, g.revoked_at, g.revoked_by
    FROM data.api_grant g
    WHERE g.id = p_id;
END;
$$
