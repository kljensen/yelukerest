-- ---------------------------------------------------------------------------
-- Immutability
-- ---------------------------------------------------------------------------
-- Permission rows are written by data.create_api_grant_rows and by nothing
-- else. The function opens the window by naming the grant it is building in a
-- transaction-local setting; an insert for any other grant, and every update
-- or delete, is refused. This is a guard against a later migration or an
-- admin session writing permissions by hand, not a privilege boundary: the
-- only roles that can reach these tables at all are the migrator and, read
-- only, `api`.
CREATE FUNCTION data.api_grant_permissions_are_immutable() RETURNS trigger LANGUAGE plpgsql SET search_path TO pg_catalog, pg_temp AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF current_setting('yeluke.api_grant_in_creation', true) = NEW.grant_id::text THEN
            RETURN NEW;
        END IF;
    END IF;
    RAISE EXCEPTION 'api grant permissions are fixed at creation; revoke the grant and create another'
        USING ERRCODE = '42501';
END;
$$
; ALTER FUNCTION data.api_grant_permissions_are_immutable() OWNER TO yelukerest_migrator
; CREATE TRIGGER tg_api_grant_assignment_immutable BEFORE INSERT OR DELETE OR UPDATE ON data.api_grant_assignment FOR EACH ROW EXECUTE FUNCTION data.api_grant_permissions_are_immutable()
; CREATE TRIGGER tg_api_grant_assignment_field_immutable BEFORE INSERT OR DELETE OR UPDATE ON data.api_grant_assignment_field FOR EACH ROW EXECUTE FUNCTION data.api_grant_permissions_are_immutable()
;
-- The grant row itself changes exactly once, when it is revoked, and then only
-- in the two revocation columns. Deleting a grant needs no trigger: every grant
-- has at least one permission row, and the restrictive foreign keys refuse to
-- orphan it.
CREATE FUNCTION data.api_grant_allows_only_first_revocation() RETURNS trigger LANGUAGE plpgsql SET search_path TO pg_catalog, pg_temp AS $$
BEGIN
    IF OLD.revoked_at IS NULL
       AND NEW.revoked_at IS NOT NULL
       AND NEW.revoked_by IS NOT NULL
       AND NEW.id = OLD.id
       AND NEW.name = OLD.name
       AND NEW.created_by = OLD.created_by
       AND NEW.created_at = OLD.created_at
       AND NEW.expires_at = OLD.expires_at THEN
        RETURN NEW;
    END IF;
    RAISE EXCEPTION 'an api grant changes only by being revoked, once; revoke it and create another'
        USING ERRCODE = '42501';
END;
$$
