-- ---------------------------------------------------------------------------
-- API view -- faculty only, and never a credential
-- ---------------------------------------------------------------------------
-- `permissions` has the shape api.create_api_grant accepts, so what faculty
-- see is what was asked for.
CREATE VIEW api.api_grants WITH (security_barrier=true) AS
    SELECT
        g.id, g.name, g.created_by, g.created_at, g.expires_at, g.revoked_by,
        g.revoked_at, g.revoked_at IS NULL
        AND g.expires_at > current_timestamp AS is_active,
        (
            SELECT
                jsonb_agg(jsonb_build_object('assignment_slug', ga.assignment_slug, 'identity', to_jsonb(ga.identity), 'field_slugs', (
                    SELECT jsonb_agg(f.field_slug ORDER BY f.field_slug)
                    FROM data.api_grant_assignment_field f
                    WHERE
                        f.grant_id = ga.grant_id
                        AND f.assignment_slug = ga.assignment_slug
                )) ORDER BY ga.assignment_slug)
            FROM data.api_grant_assignment ga
            WHERE ga.grant_id = g.id
        ) AS permissions
    FROM data.api_grant g
    WHERE request.user_role() = 'faculty'::text
