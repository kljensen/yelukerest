; CREATE TRIGGER tg_api_grant_first_revocation_only BEFORE UPDATE ON data.api_grant FOR EACH ROW EXECUTE FUNCTION data.api_grant_allows_only_first_revocation()
;
-- ---------------------------------------------------------------------------
-- Creation: the validated insert
-- ---------------------------------------------------------------------------
-- p_assignments is [{"assignment_slug": ..., "identity": [...], "field_slugs":
-- [...]}, ...]. Every rule is checked here and any failure raises, so the
-- caller's transaction gets all the rows or none. Not exposed through the API:
-- step 2 wraps it in api.create_api_grant, which must also sign and return the
-- credential in the same transaction.
CREATE FUNCTION data.create_api_grant_rows(p_name text, p_assignments jsonb, p_expires_at timestamp with time zone, p_created_by int) RETURNS int LANGUAGE plpgsql SET search_path TO pg_catalog, data, pg_temp AS $$
DECLARE
    identity_names CONSTANT text[] := ARRAY['netid', 'name', 'nickname', 'team_nickname'];
    max_lifetime CONSTANT interval := interval '180 days';
    new_id int;
    entry jsonb;
    entry_slug text;
    entry_identity text[];
    entry_fields text[];
    offending text[];
BEGIN
    IF p_name IS NULL OR char_length(p_name) NOT BETWEEN 3 AND 80 THEN
        RAISE EXCEPTION 'a grant name of 3 to 80 characters is required' USING ERRCODE = '22023';
    END IF;
    IF p_expires_at IS NULL OR p_expires_at <= current_timestamp THEN
        RAISE EXCEPTION 'expires_at must be in the future' USING ERRCODE = '22023';
    END IF;
    IF p_expires_at > current_timestamp + max_lifetime THEN
        RAISE EXCEPTION 'expires_at may be at most % from now (% requested, latest allowed is %)',
            max_lifetime, p_expires_at, current_timestamp + max_lifetime
            USING ERRCODE = '22023';
    END IF;
    IF p_created_by IS NULL THEN
        RAISE EXCEPTION 'a creating user is required' USING ERRCODE = '22023';
    END IF;
    IF p_assignments IS NULL OR jsonb_typeof(p_assignments) <> 'array' OR jsonb_array_length(p_assignments) = 0 THEN
        RAISE EXCEPTION 'p_assignments must be a non-empty array of {assignment_slug, identity, field_slugs}'
            USING ERRCODE = '22023';
    END IF;
    IF (SELECT count(*) <> count(DISTINCT e ->> 'assignment_slug') FROM jsonb_array_elements(p_assignments) e) THEN
        RAISE EXCEPTION 'each assignment may appear once in p_assignments' USING ERRCODE = '22023';
    END IF;

    INSERT INTO data.api_grant (name, created_by, expires_at)
    VALUES (p_name, p_created_by, p_expires_at)
    RETURNING data.api_grant.id INTO new_id;

    -- Open the one window in which permission rows may be written (see
    -- data.api_grant_permissions_are_immutable). Transaction-local, so a
    -- failure below discards it with everything else.
    PERFORM set_config('yeluke.api_grant_in_creation', new_id::text, true);

    FOR entry IN SELECT e FROM jsonb_array_elements(p_assignments) e LOOP
        IF jsonb_typeof(entry) <> 'object' THEN
            RAISE EXCEPTION 'each p_assignments entry must be an object' USING ERRCODE = '22023';
        END IF;
        SELECT array_agg(k ORDER BY k) INTO offending
        FROM jsonb_object_keys(entry) k
        WHERE k NOT IN ('assignment_slug', 'identity', 'field_slugs');
        IF offending IS NOT NULL THEN
            RAISE EXCEPTION 'unknown key(s) in p_assignments entry: %', array_to_string(offending, ', ')
                USING ERRCODE = '22023';
        END IF;
        IF jsonb_typeof(entry -> 'assignment_slug') IS DISTINCT FROM 'string' THEN
            RAISE EXCEPTION 'assignment_slug must be a string' USING ERRCODE = '22023';
        END IF;
        entry_slug := entry ->> 'assignment_slug';
        IF NOT EXISTS (SELECT 1 FROM data.assignment a WHERE a.slug = entry_slug) THEN
            RAISE EXCEPTION 'unknown assignment %', entry_slug USING ERRCODE = '22023';
        END IF;

        -- Both lists must be arrays of strings: a JSON null or number is
        -- refused rather than cast. Then no duplicates, then the vocabulary.
        IF jsonb_typeof(entry -> 'identity') IS DISTINCT FROM 'array'
           OR EXISTS (SELECT 1 FROM jsonb_array_elements(entry -> 'identity') i WHERE jsonb_typeof(i) <> 'string') THEN
            RAISE EXCEPTION 'identity for % must be an array of strings', entry_slug USING ERRCODE = '22023';
        END IF;
        SELECT coalesce(array_agg(i), '{}') INTO entry_identity FROM jsonb_array_elements_text(entry -> 'identity') i;
        IF cardinality(entry_identity) <> (SELECT count(DISTINCT i) FROM unnest(entry_identity) i) THEN
            RAISE EXCEPTION 'identity for % lists an attribute twice', entry_slug USING ERRCODE = '22023';
        END IF;
        IF NOT (entry_identity <@ identity_names) THEN
            RAISE EXCEPTION 'identity for % may only name %', entry_slug, array_to_string(identity_names, ', ')
                USING ERRCODE = '22023';
        END IF;

        IF jsonb_typeof(entry -> 'field_slugs') IS DISTINCT FROM 'array'
           OR EXISTS (SELECT 1 FROM jsonb_array_elements(entry -> 'field_slugs') f WHERE jsonb_typeof(f) <> 'string') THEN
            RAISE EXCEPTION 'field_slugs for % must be an array of strings', entry_slug USING ERRCODE = '22023';
        END IF;
        SELECT coalesce(array_agg(f), '{}') INTO entry_fields FROM jsonb_array_elements_text(entry -> 'field_slugs') f;
        IF cardinality(entry_fields) = 0 THEN
            RAISE EXCEPTION 'at least one field of % must be granted', entry_slug USING ERRCODE = '22023';
        END IF;
        IF cardinality(entry_fields) <> (SELECT count(DISTINCT f) FROM unnest(entry_fields) f) THEN
            RAISE EXCEPTION 'field_slugs for % lists a field twice', entry_slug USING ERRCODE = '22023';
        END IF;
        SELECT array_agg(f ORDER BY f) INTO offending
        FROM unnest(entry_fields) f
        WHERE NOT EXISTS (
            SELECT 1 FROM data.assignment_field af
            WHERE af.assignment_slug = entry_slug AND af.slug = f
        );
        IF offending IS NOT NULL THEN
            RAISE EXCEPTION 'unknown field(s) of %: %', entry_slug, array_to_string(offending, ', ')
                USING ERRCODE = '22023';
        END IF;

        INSERT INTO data.api_grant_assignment (grant_id, assignment_slug, identity)
        VALUES (new_id, entry_slug, entry_identity);
        INSERT INTO data.api_grant_assignment_field (grant_id, assignment_slug, field_slug)
        SELECT new_id, entry_slug, f FROM unnest(entry_fields) f;
    END LOOP;

    PERFORM set_config('yeluke.api_grant_in_creation', '', true);
    RETURN new_id;
END;
$$
