-- What the graded artifact actually was, at each student's deadline (#22).
--
-- Graders clone the student repository and grade HEAD, so nothing stops a push
-- after the deadline from changing what gets graded. The old patch for that was
-- scripts/remove-student-write-to-github.sh, which greps repository names by
-- substring and takes extensions as a hand-passed skip list -- so an extension
-- granted after it runs is simply missed, which is Classroom's own documented
-- bug reproduced.
--
-- Repository lock says "the student cannot change this". What grading needs is
-- "this exact artifact is what was graded", which is stronger, auditable, and
-- survives a force-push, a December regrade, and an assignment whose server has
-- to keep running all semester.
--
-- So at each student's effective deadline -- assignment_grade_exception.closed_at
-- if one applies, else assignment.closed_at, which is exactly the expression the
-- RLS on data.assignment_submission already evaluates -- capture the resolved
-- commit SHA, a durable `git bundle`, and the bundle's SHA-256 digest.
--
-- The SHA alone is not enough. A force-push cannot alter a commit but it can
-- make the commit unreachable, and GitHub does not promise to retain unreachable
-- objects. A tarball is also wrong: `version-control` is an assignment *about*
-- git history and a tarball discards it. The bundle is the artifact; the SHA
-- says which commit inside it to check out; the digest says the bundle is the
-- one that was captured.
--
-- Consumer: the course-side snapshot runner in yale-mgt-656-fall-2026/admin#22.
--
-- Deployed inside a transaction Zapadka opens and commits.
-- Do not write BEGIN, COMMIT, ROLLBACK, or SAVEPOINT here.

-- ---------------------------------------------------------------------------
-- data.assignment_repository_snapshot
-- ---------------------------------------------------------------------------
-- One row per capture *attempt*, not one row per repository.
--
-- Failures are rows, not absences. A capture that could not resolve HEAD, could
-- not push the bundle, or produced a digest that did not match on read-back
-- must leave a row behind saying so. The audit trail is the entire point of
-- this table, and a missing row is indistinguishable from "not due yet" -- which
-- is precisely the state a silently failing runner would be mistaken for, for
-- as long as nobody looked.
CREATE TABLE data.assignment_repository_snapshot (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- The repository this is a snapshot of. NO ACTION on delete, deliberately:
    -- a repository record that has been snapshotted cannot be deleted until its
    -- snapshots are, which is the same protection data.assignment_grade gives
    -- data.assignment_submission. Deleting the mapping would strand the
    -- snapshots as rows about nothing, and "we graded commit X of some
    -- repository" is not an audit trail.
    --
    -- ON UPDATE CASCADE is inherited habit rather than need -- the referenced
    -- column is an identity and does not move -- and costs nothing.
    assignment_repository_id INT NOT NULL
        REFERENCES data.assignment_repository(id)
        ON UPDATE CASCADE,

    -- The deadline this capture was made *for*, copied in rather than derived on
    -- read. It has to be stored: the effective deadline is a live computation
    -- over assignment.closed_at and any exception, and both of those move. A
    -- snapshot whose deadline was re-derived at read time would silently start
    -- claiming to be the capture for whatever deadline is current now, which
    -- destroys the one fact the row exists to record.
    --
    -- It is also what makes "is this repository due again" answerable: see
    -- api.assignment_repository_snapshots_due below.
    effective_closed_at TIMESTAMP WITH TIME ZONE NOT NULL,

    -- When the capture was actually observed, which is *not* the deadline. There
    -- is a real window between the two -- the runner polls every few minutes --
    -- and git commit timestamps are user-controlled, so they cannot close it.
    -- Recording the true capture time is the honest option; narrowing the window
    -- is a matter of polling more often, and closing it entirely would need a
    -- short-lived write lock on the forge. Record reality either way.
    captured_at TIMESTAMP WITH TIME ZONE
        NOT NULL
        DEFAULT current_timestamp,

    -- A capture cannot precede the deadline it claims to capture. This is the
    -- table's central invariant, and without it a row asserting "this is what
    -- existed at the deadline" could have been taken an hour before it.
    CONSTRAINT captured_after_deadline CHECK (captured_at >= effective_closed_at),

    -- The resolved commit. Forty hex for SHA-1 and sixty-four for SHA-256,
    -- because git is midway through that migration and a repository created with
    -- an object-format of sha256 hands back the longer one. Lowercase only: git
    -- emits lowercase, and accepting both cases would make one commit two
    -- strings.
    --
    -- Nullable, because a failed capture has no commit -- that is what makes it a
    -- failure. The completeness constraint below is what stops a *successful*
    -- one from omitting it.
    commit_sha TEXT
        CHECK (commit_sha ~ '^[0-9a-f]{40}$' OR commit_sha ~ '^[0-9a-f]{64}$'),

    -- Where the bundle lives. Plain text on purpose: S3, a mounted volume, or
    -- somewhere else entirely is an operational choice, and pinning it into the
    -- schema would make moving the store a migration. The issue's preference is
    -- that it be independent of the student repository and ideally outside the
    -- org; nothing here can enforce that, and pretending otherwise with a CHECK
    -- on the hostname would only be a lie with a maintenance cost.
    --
    -- A location, never a credential. A presigned URL does not belong here: it
    -- expires, which makes it useless to a December regrade, and students can
    -- read this column. Authorization to fetch the bundle lives in the store.
    bundle_uri TEXT
        CHECK (char_length(bundle_uri) BETWEEN 1 AND 2048),

    -- SHA-256 of the bundle bytes, so a grader can prove the file they fetched is
    -- the file that was captured. Sixty-four lowercase hex, exactly -- a digest
    -- that is sometimes uppercase and sometimes truncated is a digest nobody
    -- compares.
    bundle_sha256 TEXT
        CHECK (bundle_sha256 ~ '^[0-9a-f]{64}$'),

    -- Whether the capture was verified end to end: the bundle was written, read
    -- back, and its digest recomputed to the value recorded above. This is not
    -- "the runner did not crash". Everything downstream keys on it, so it is the
    -- one flag worth being strict about.
    is_verified BOOLEAN NOT NULL DEFAULT FALSE,

    -- Why it failed, when it failed. Required on failure and forbidden on
    -- success, per the constraint below.
    error TEXT
        CHECK (error IS NULL OR char_length(btrim(error)) BETWEEN 1 AND 8192),

    -- A verified snapshot is complete or it is not verified. An unverified one
    -- says why. Both halves matter: a verified row missing its bundle URI is a
    -- promise the grader cannot cash, and an unverified row with no error is a
    -- failure nobody can act on -- it reads as "something went wrong once".
    CONSTRAINT verified_snapshot_is_complete CHECK (
        (
            is_verified
            AND commit_sha IS NOT NULL
            AND bundle_uri IS NOT NULL
            AND bundle_sha256 IS NOT NULL
            AND error IS NULL
        )
        OR
        (NOT is_verified AND error IS NOT NULL)
    ),

    -- Supersession, not deletion. When an extension moves a deadline later, the
    -- snapshot taken at the old deadline is still a true statement about what
    -- existed then, and deleting it would erase exactly the history a grade
    -- dispute needs. It stops being *current*, which is a different claim, and
    -- this column is where that claim is recorded -- with the time, because "when
    -- did this stop being the artifact we grade" is the question an audit asks.
    superseded_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT superseded_after_captured
        CHECK (superseded_at IS NULL OR superseded_at >= captured_at),

    created_at TIMESTAMP WITH TIME ZONE
        NOT NULL
        DEFAULT current_timestamp,
    updated_at TIMESTAMP WITH TIME ZONE
        NOT NULL
        DEFAULT current_timestamp,
    CONSTRAINT updated_after_created CHECK (updated_at >= created_at)
);

-- "The current snapshot for this repository" resolves to one row or none, and
-- the database is what guarantees it. A grader who has to pick between two
-- candidate artifacts is back where this table started.
--
-- Keyed on the repository alone, not on (repository, deadline): a repository has
-- one artifact that gets graded at a time, and a capture for a new deadline
-- becomes current by superseding the old one rather than by sitting alongside
-- it. Retiring the old row is left to the writer that has just proved it holds a
-- newer one -- the database's job here is to make two current snapshots
-- unrepresentable, not to guess when one should be retired.
--
-- The predicate is narrowed to verified rows so that failures accumulate freely.
-- A repository that fails ten times in a row has ten rows, which is the shape of
-- the evidence; a unique index over all rows would let the first failure block
-- every retry from being recorded.
--
-- Partial-unique is the shape data.assignment_repository already uses for its
-- own per-student and per-team rules, for the same reason: the interesting
-- uniqueness is always conditional.
CREATE UNIQUE INDEX assignment_repository_snapshot_current
    ON data.assignment_repository_snapshot (assignment_repository_id)
    WHERE is_verified AND superseded_at IS NULL;

-- Plain btree covering the foreign key's referencing column, in the
-- constraint's own column order. tests/db/foreign-key-indexes.sql requires this
-- of every foreign key in `data` and ignores any index carrying a predicate --
-- correctly, since a partial index cannot serve a referential integrity check --
-- so the partial unique above does not count.
--
-- `effective_closed_at` is appended rather than given a second index. The test
-- and the referential check both match on a leading-column prefix, and every
-- interesting lookup here -- "is there a snapshot for this repository at this
-- deadline" -- wants both columns anyway.
CREATE INDEX idx_assignment_repository_snapshot_repository_fk
    ON data.assignment_repository_snapshot (assignment_repository_id, effective_closed_at);

-- The generic updated_at trigger, already deployed and already routed through
-- data.touched_at, so this table inherits the #308 fix rather than restating it.
-- No new function.
CREATE TRIGGER tg_assignment_repository_snapshot_update_timestamps
    BEFORE INSERT OR UPDATE
    ON data.assignment_repository_snapshot
    FOR EACH ROW
EXECUTE FUNCTION data.update_updated_at_column();

