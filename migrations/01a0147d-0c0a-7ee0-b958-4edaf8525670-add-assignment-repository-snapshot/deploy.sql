-- ---------------------------------------------------------------------------
-- api.assignment_repository_snapshots_due
-- ---------------------------------------------------------------------------
-- The work queue: which repositories need capturing right now.
--
-- This exists because the effective-deadline expression must live in one place.
-- Extensions move deadlines individually and continuously, so a runner cannot
-- schedule one job at the common deadline -- it has to poll for work that has
-- *become* due, and every client that re-derived "effective deadline" from
-- assignment.closed_at and the exception table would be one more place for the
-- definition to drift out of agreement with the RLS on
-- data.assignment_submission, which is where the definition actually comes from.
--
-- The matching rule is that RLS's, copied deliberately rather than reinvented:
-- an exception applies when it names the same assignment and either its user_id
-- or its team_nickname equals the repository's. NULL is never equal to NULL, so
-- that single predicate gives the individual/team split for free -- an individual
-- repository has a NULL team_nickname and can only match on user, and a team
-- repository has a NULL user_id and can only match on team.
--
-- At most one exception can match: data.assignment_grade_exception's two partial
-- unique indexes make (assignment, user) and (assignment, team) unique, so the
-- LEFT JOIN cannot fan out.
--
-- "Due" is three conditions:
--
--   1. The assignment is not a draft. A draft is not visible to students through
--      api.assignments and is still being written, so its closed_at is not a
--      deadline anyone is working against. The RLS this expression is copied
--      from excludes drafts for the same reason.
--
--   2. The effective deadline has passed.
--
--   3. There is no current, verified snapshot *for that same deadline*.
--
-- The third condition is where a moved deadline is handled, and matching on the
-- deadline rather than merely on the repository is the whole of it. Take a
-- repository snapshotted at its original deadline and then granted an extension:
--
--   * While the new deadline is still in the future, condition 2 fails and the
--     repository is not due. The old snapshot stays current, correctly -- it is
--     the best artifact anyone has until a newer one exists, and a window with no
--     current snapshot at all would be strictly worse.
--
--   * Once the new deadline passes, condition 3 fails to find a snapshot,
--     because the existing one records the *old* effective_closed_at. The
--     repository becomes due again on its own, with no reconciliation step and
--     nothing to remember to re-run. When the new capture lands the runner
--     supersedes the old row, and the partial unique index refuses to let it
--     forget.
--
-- Had this been keyed on the repository alone, an extension granted after a
-- capture would leave the repository permanently not-due, and the student's
-- extension would silently not apply to what was graded -- which is Classroom's
-- bug again, in a new place.
--
-- Failed attempts do not make a repository not-due; that is what makes the
-- runner's retry loop work. failed_attempt_count and last_failed_at are exposed
-- so that "retry forever" can be an operational decision rather than the only
-- available behavior, since a repository that has been deleted on the forge will
-- otherwise fail every few minutes until someone notices.
CREATE OR REPLACE VIEW api.assignment_repository_snapshots_due
WITH (security_barrier = true) AS
    SELECT
        r.id AS assignment_repository_id,
        r.assignment_slug,
        r.is_team,
        r.user_id,
        r.team_nickname,
        r.provider,
        r.provider_repo_id,
        r.provider_full_name,
        a.closed_at AS assignment_closed_at,
        d.effective_closed_at,
        f.failed_attempt_count,
        f.last_failed_at
    FROM data.assignment_repository AS r
    JOIN data.assignment AS a
        ON a.slug = r.assignment_slug
    LEFT JOIN data.assignment_grade_exception AS e
        ON e.assignment_slug = r.assignment_slug
        AND (e.user_id = r.user_id OR e.team_nickname = r.team_nickname)
    -- Naming the expression once, so the three places that need it cannot drift
    -- apart from each other the way copies of it would.
    CROSS JOIN LATERAL (
        SELECT COALESCE(e.closed_at, a.closed_at) AS effective_closed_at
    ) AS d
    CROSS JOIN LATERAL (
        SELECT
            count(*)::int AS failed_attempt_count,
            max(s.captured_at) AS last_failed_at
        FROM data.assignment_repository_snapshot AS s
        WHERE s.assignment_repository_id = r.id
        AND s.effective_closed_at = d.effective_closed_at
        AND NOT s.is_verified
    ) AS f
    WHERE NOT a.is_draft
    AND d.effective_closed_at <= current_timestamp
    AND NOT EXISTS (
        SELECT 1
        FROM data.assignment_repository_snapshot AS s
        WHERE s.assignment_repository_id = r.id
        AND s.effective_closed_at = d.effective_closed_at
        AND s.is_verified
        AND s.superseded_at IS NULL
    );

ALTER VIEW api.assignment_repository_snapshots_due OWNER TO api;

