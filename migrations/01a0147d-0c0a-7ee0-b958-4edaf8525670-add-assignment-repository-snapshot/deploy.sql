-- Faculty read and write. A student reads the snapshots of their own repository
-- and nothing else. Exactly the split data.assignment_repository uses, and
-- exactly the same reasoning: a student needs to be able to ask "which commit of
-- mine was graded" without a faculty member in the loop, which is the whole
-- support path a regrade dispute runs down. Writing is faculty-only, because a
-- student who could write here could nominate a different artifact as the graded
-- one, which is the property the table exists to establish.
--
-- Ownership is resolved through data.assignment_repository rather than
-- duplicated onto this table. That keeps one definition of who owns a
-- repository, including the live-team rule -- a student moved off a team loses
-- the team repository on the forge at the same moment, so live membership is the
-- answer that stays true here too.
CREATE POLICY assignment_repository_snapshot_access_policy
    ON data.assignment_repository_snapshot TO api
USING (
    (request.user_role() = 'faculty')
    OR
    (
        request.user_role() = ANY('{student,ta}'::text[])
        AND EXISTS (
            SELECT 1
            FROM data.assignment_repository AS r
            WHERE r.id = assignment_repository_snapshot.assignment_repository_id
            AND (
                (NOT r.is_team AND request.user_id() = r.user_id)
                OR
                (r.is_team AND EXISTS (
                    SELECT 1
                    FROM data."user" AS u
                    WHERE u.id = request.user_id()
                    AND u.team_nickname = r.team_nickname
                ))
            )
        )
    )
) WITH CHECK (
    request.user_role() = 'faculty'
);

